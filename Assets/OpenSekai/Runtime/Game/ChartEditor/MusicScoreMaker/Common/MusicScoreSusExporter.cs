using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using Sekai.Live;
using Sekai.MusicScoreMaker.Ingame.Models;
using Sekai.MusicScoreMaker.Ingame.Utilities;

namespace Sekai.MusicScoreMaker.Common
{
	/// <summary>
	/// Writes MusicScoreMakerData as SUS text in the layout Sekai.SUS.Converter reads, so importing the result
	/// gives back the same notes, events and Skill/Fever markers. Things SUS cannot hold are listed in Warnings.
	/// </summary>
	public static class MusicScoreSusExporter
	{
		private const string L10nTable = "ChartEditor";

		public sealed class Metadata
		{
			public string Title;
			public string Artist;
			public string Designer;
			public string Wave;
			public string Jacket;
			public int PlayLevel;

			/// <summary>#WAVEOFFSET: minus the chart's fillerSec (SUS tools put the music this many seconds after the chart's start).</summary>
			public float WaveOffset;
		}

		public sealed class Result
		{
			public string Text;
			public List<string> Warnings = new List<string>();
		}

		private const int TicksPerBeat = 480;
		private const int MaxBar = 999;
		private const int MaxLongNoCount = 36;
		private const string LaneChars = "23456789abcd";
		private const string WidthChars = "123456789abc";
		private const string Base36Chars = "0123456789abcdefghijklmnopqrstuvwxyz";
		private const int LaneCount = 12;

		// Notes that must not merge with another on the same tick and lane are written 1/8, 2/8 or 3/8 of a tick late.
		// That keeps them apart in the converter, and its rounding still puts them back on the original tick.
		private const int SubTicksPerTick = 8;
		private const int MaxSubTickSlot = 3;

		// The converter merges rows that land on the same tick and lane in file order, and some merges only
		// work one way round (a Friction tap has to come before the slide or flick it turns into a FrictionLong or
		// FrictionFlick; a skip tap has to come first so the relay keeps its skip flag). So every tap row is written
		// first, then the flick/ease rows, then slides, then guides.
		private const int GroupTap = 0;
		private const int GroupDirectional = 1;
		private const int GroupSlide = 2;
		private const int GroupGuide = 3;

		public static Result Export(MusicScoreMakerData data, Metadata metadata = null)
		{
			Result result = new Result();
			if (data == null)
			{
				result.Warnings.Add(L10n.Get(L10nTable, "sus.empty"));
				result.Text = string.Empty;
				return result;
			}

			List<MusicScoreEventData> events = (data.MusicScoreEventDataList ?? new List<MusicScoreEventData>()).Where(e => e != null).OrderBy(e => e.ticks).ToList();
			BarGrid grid = new BarGrid(events, result.Warnings);
			RowSet rows = new RowSet(grid, result.Warnings);

			StringBuilder sb = new StringBuilder();
			WriteHeader(sb, metadata);

			foreach ((int bar, float beats) in grid.TimeSignatures)
			{
				sb.Append('#').Append(bar.ToString("D3", CultureInfo.InvariantCulture)).Append("02: ").Append(FormatFloat(beats)).Append('\n');
			}
			sb.Append('\n');

			WriteBpm(sb, events, grid, result.Warnings);
			sb.Append('\n');

			sb.Append("#TIL00: \"").Append(BuildTimeline(events, MusicScoreEventType.HighSpeed, grid)).Append("\"\n");
			sb.Append("#HISPEED 00\n");
			sb.Append("#MEASUREHS 00\n");
			string volumeTimeline = BuildTimeline(events, MusicScoreEventType.SeVolume, grid);
			if (volumeTimeline.Length > 0)
			{
				sb.Append("#VOLUME: \"").Append(volumeTimeline).Append("\"\n");
			}
			sb.Append('\n');

			AddSkillFeverMarkers(rows, data.SkillFeverMarkerList, result.Warnings);
			AddNotes(rows, data.NoteList, result.Warnings);
			rows.WriteTo(sb);

			result.Text = sb.ToString();
			return result;
		}

		private static void WriteHeader(StringBuilder sb, Metadata metadata)
		{
			sb.Append("This file was generated by OpenSekai.\n");
			sb.Append("#TITLE \"").Append(Quote(metadata?.Title)).Append("\"\n");
			sb.Append("#ARTIST \"").Append(Quote(metadata?.Artist)).Append("\"\n");
			sb.Append("#DESIGNER \"").Append(Quote(metadata?.Designer)).Append("\"\n");
			sb.Append("#PLAYLEVEL ").Append(metadata != null && metadata.PlayLevel > 0 ? metadata.PlayLevel.ToString(CultureInfo.InvariantCulture) : string.Empty).Append('\n');
			sb.Append("#WAVE \"").Append(Quote(metadata?.Wave)).Append("\"\n");
			sb.Append("#WAVEOFFSET ").Append(FormatFloat(metadata?.WaveOffset ?? 0f)).Append('\n');
			sb.Append("#JACKET \"").Append(Quote(metadata?.Jacket)).Append("\"\n");
			sb.Append('\n');
			sb.Append("#REQUEST \"ticks_per_beat ").Append(TicksPerBeat.ToString(CultureInfo.InvariantCulture)).Append("\"\n");
			sb.Append('\n');
		}

		private static void WriteBpm(StringBuilder sb, List<MusicScoreEventData> events, BarGrid grid, List<string> warnings)
		{
			// Last value wins on a tick, the same as MusicScoreMakerUtility.ConvertMusicScoreInfo.
			SortedDictionary<long, float> bpmByTicks = new SortedDictionary<long, float>();
			foreach (MusicScoreEventData evt in events)
			{
				if (evt.eventType == MusicScoreEventType.BPM && TryGetFloat(evt.changeValue, out float bpm) && bpm > 0f)
				{
					bpmByTicks[Math.Max(0L, evt.ticks)] = bpm;
				}
			}
			if (!bpmByTicks.ContainsKey(0L))
			{
				// The editor and the converter both fall back to 120 before the first BPM event.
				bpmByTicks[0L] = 120f;
			}

			Dictionary<string, string> idByValue = new Dictionary<string, string>();
			List<(long ticks, string id)> placements = new List<(long, string)>();
			float? previous = null;
			foreach (KeyValuePair<long, float> pair in bpmByTicks)
			{
				if (previous.HasValue && previous.Value == pair.Value)
				{
					continue;
				}
				previous = pair.Value;
				string text = FormatFloat(pair.Value);
				if (!idByValue.TryGetValue(text, out string id))
				{
					int index = idByValue.Count + 1;
					if (index >= 36 * 36)
					{
						warnings.Add(L10n.Get(L10nTable, "sus.tooManyBpms"));
						break;
					}
					id = (Base36Chars[index / 36].ToString() + Base36Chars[index % 36]).ToUpperInvariant();
					idByValue[text] = id;
					sb.Append("#BPM").Append(id).Append(": ").Append(text).Append('\n');
				}
				placements.Add((pair.Key, id));
			}

			RowSet bpmRows = new RowSet(grid, warnings);
			foreach ((long ticks, string id) in placements)
			{
				bpmRows.Add(GroupTap, ticks, "08", id, 1f, null);
			}
			bpmRows.WriteTo(sb);
		}

		private static string BuildTimeline(List<MusicScoreEventData> events, MusicScoreEventType eventType, BarGrid grid)
		{
			SortedDictionary<long, float> valueByTicks = new SortedDictionary<long, float>();
			foreach (MusicScoreEventData evt in events)
			{
				if (evt.eventType == eventType && TryGetFloat(evt.changeValue, out float value))
				{
					valueByTicks[Math.Max(0L, evt.ticks)] = value;
				}
			}
			List<string> items = new List<string>();
			float previous = 1f;
			foreach (KeyValuePair<long, float> pair in valueByTicks)
			{
				if (pair.Value == previous)
				{
					continue;
				}
				previous = pair.Value;
				grid.Locate(pair.Key, out int bar, out long offset);
				items.Add(bar.ToString(CultureInfo.InvariantCulture) + "'" + offset.ToString(CultureInfo.InvariantCulture) + ":" + FormatFloat(pair.Value));
			}
			return string.Join(", ", items);
		}

		private static void AddSkillFeverMarkers(RowSet rows, List<MusicScoreSkillFeverMarker> markers, List<string> warnings)
		{
			if (markers == null)
			{
				return;
			}
			foreach (MusicScoreSkillFeverMarker marker in markers)
			{
				if (marker == null)
				{
					continue;
				}
				switch (marker.type)
				{
				case MusicScoreSkillFeverMarkerType.Skill:
					rows.Add(GroupTap, marker.ticks, "10", "41", 1f, null);
					break;
				case MusicScoreSkillFeverMarkerType.FeverBegin:
					rows.Add(GroupTap, marker.ticks, "1f", "11", 1f, null);
					break;
				case MusicScoreSkillFeverMarkerType.FeverStart:
					rows.Add(GroupTap, marker.ticks, "1f", "21", 1f, null);
					break;
				}
			}
		}

		private static void AddNotes(RowSet rows, List<MusicScoreNoteBase> noteList, List<string> warnings)
		{
			if (noteList == null || noteList.Count == 0)
			{
				return;
			}
			Dictionary<int, MusicScoreNoteBase> byId = new Dictionary<int, MusicScoreNoteBase>();
			foreach (MusicScoreNoteBase note in noteList)
			{
				if (note != null)
				{
					byId[note.id] = note;
				}
			}

			List<List<MusicScoreNoteBase>> slideChains = new List<List<MusicScoreNoteBase>>();
			List<List<MusicScoreNoteBase>> guideChains = new List<List<MusicScoreNoteBase>>();
			List<MusicScoreNoteBase> singles = new List<MusicScoreNoteBase>();
			int droppedChildren = 0;
			foreach (MusicScoreNoteBase note in noteList)
			{
				if (note == null || (note.previousConnectionId != -1 && byId.ContainsKey(note.previousConnectionId)))
				{
					continue;
				}
				List<MusicScoreNoteBase> chain = FollowChain(note, byId);
				if (IsGuideRoot(note))
				{
					guideChains.Add(chain);
				}
				else if (IsSlideRoot(note))
				{
					slideChains.Add(chain);
				}
				else
				{
					// Live play only follows chains that start with a long note, so the rest of such a chain never plays.
					droppedChildren += chain.Count - 1;
					singles.Add(note);
				}
			}
			if (droppedChildren > 0)
			{
				warnings.Add(L10n.Format(L10nTable, "sus.droppedChildren", droppedChildren));
			}

			// The converter keys notes by (time, left lane), so notes stacked on the same tick and lane (say a slide
			// ending where the next one starts) would be merged into one. Each extra note is written a fraction of a
			// tick later instead: it stays a separate note, and reading it back rounds it to the same tick again.
			Dictionary<(long, int), MusicScoreNoteBase> playablePositions = new Dictionary<(long, int), MusicScoreNoteBase>();
			Dictionary<(long, int), int> playableCounts = new Dictionary<(long, int), int>();
			int overlapCount = 0;
			IEnumerable<MusicScoreNoteBase> playableNotes = singles.Concat(slideChains.SelectMany(chain => chain)).Where(note => note.noteBaseType != MusicScoreNoteBase.NoteBaseType.LongHoldCombo);
			foreach (IGrouping<(long, int), MusicScoreNoteBase> group in playableNotes.GroupBy(note => (note.ticks, note.laneStart)))
			{
				// Points that continue a slide go first, so the note left on the exact tick is the one a guide there
				// would most likely be drawn over.
				List<MusicScoreNoteBase> ordered = group.OrderBy(note => note.previousConnectionId != -1 ? 0 : 1).ToList();
				playablePositions[group.Key] = ordered[0];
				playableCounts[group.Key] = ordered.Count;
				for (int i = 0; i < ordered.Count; i++)
				{
					if (i > MaxSubTickSlot)
					{
						overlapCount++;
					}
					rows.Slots[ordered[i]] = Math.Min(i, MaxSubTickSlot);
				}
			}
			if (overlapCount > 0)
			{
				warnings.Add(L10n.Format(L10nTable, "sus.sameStartOverlap", MaxSubTickSlot + 1, overlapCount));
			}

			int unsupportedSingles = 0;
			foreach (MusicScoreNoteBase note in singles)
			{
				if (!AddSingleNote(rows, note))
				{
					unsupportedSingles++;
				}
			}
			if (unsupportedSingles > 0)
			{
				warnings.Add(L10n.Format(L10nTable, "sus.isolatedRelay", unsupportedSingles));
			}

			AddSlides(rows, slideChains, warnings);
			AddGuides(rows, guideChains, playablePositions, playableCounts, warnings);
		}

		private static List<MusicScoreNoteBase> FollowChain(MusicScoreNoteBase root, Dictionary<int, MusicScoreNoteBase> byId)
		{
			List<MusicScoreNoteBase> chain = new List<MusicScoreNoteBase> { root };
			HashSet<int> visited = new HashSet<int> { root.id };
			MusicScoreNoteBase current = root;
			while (current.nextConnectionId != -1 && byId.TryGetValue(current.nextConnectionId, out MusicScoreNoteBase next) && visited.Add(next.id))
			{
				chain.Add(next);
				current = next;
			}
			return chain;
		}

		private static bool IsSlideRoot(MusicScoreNoteBase note)
		{
			return note.noteBaseType == MusicScoreNoteBase.NoteBaseType.Long
				|| note.noteBaseType == MusicScoreNoteBase.NoteBaseType.FrictionLong
				|| note.noteBaseType == MusicScoreNoteBase.NoteBaseType.FrictionHideLong;
		}

		private static bool IsGuideRoot(MusicScoreNoteBase note)
		{
			return note.noteBaseType == MusicScoreNoteBase.NoteBaseType.Guide
				|| note.noteBaseType == MusicScoreNoteBase.NoteBaseType.GuideEnd
				|| note.noteBaseType == MusicScoreNoteBase.NoteBaseType.GuideHiddenConnection;
		}

		private static bool AddSingleNote(RowSet rows, MusicScoreNoteBase note)
		{
			int tapCode;
			if (note.isSkip || note.category == NoteCategory.Skip)
			{
				tapCode = 3;
			}
			else if (note.noteBaseType == MusicScoreNoteBase.NoteBaseType.Connection || note.noteBaseType == MusicScoreNoteBase.NoteBaseType.HiddenConnection || note.noteBaseType == MusicScoreNoteBase.NoteBaseType.LongHoldCombo)
			{
				return note.noteBaseType == MusicScoreNoteBase.NoteBaseType.LongHoldCombo;
			}
			else
			{
				tapCode = GetTapCode(note);
				if (tapCode == 0)
				{
					tapCode = 1;
				}
			}
			if (!TryGetLane(note, out string laneChar, out char widthChar))
			{
				return false;
			}
			rows.Add(GroupTap, note.ticks, "1" + laneChar, Code(tapCode, widthChar), note.speedRatio, note);
			AddFlickRow(rows, note, laneChar, widthChar);
			return true;
		}

		private static void AddSlides(RowSet rows, List<List<MusicScoreNoteBase>> chains, List<string> warnings)
		{
			Dictionary<List<MusicScoreNoteBase>, char> longNoByChain = AssignLongNos(chains, warnings, "sus.tooManyLongNotes");
			foreach (List<MusicScoreNoteBase> chain in chains)
			{
				if (!longNoByChain.TryGetValue(chain, out char longNo))
				{
					continue;
				}
				for (int i = 0; i < chain.Count; i++)
				{
					MusicScoreNoteBase note = chain[i];
					if (note.noteBaseType == MusicScoreNoteBase.NoteBaseType.LongHoldCombo || !TryGetLane(note, out string laneChar, out char widthChar))
					{
						continue;
					}
					int slideCode;
					if (i == 0)
					{
						slideCode = 1;
					}
					else if (note.noteBaseType == MusicScoreNoteBase.NoteBaseType.Connection)
					{
						slideCode = 3;
					}
					else if (note.noteBaseType == MusicScoreNoteBase.NoteBaseType.HiddenConnection)
					{
						slideCode = 5;
					}
					else
					{
						slideCode = 2;
					}

					// Points after the start inherit Critical from a critical start when read back (NoteBase.SetParentNote),
					// so they only need their own critical tap when the start is not critical.
					bool inheritsCritical = i > 0 && chain[0].type == NoteType.Critical;
					int tapCode = i > 0 && note.isSkip ? 3 : GetTapCode(note, inheritsCritical);
					if (tapCode != 0)
					{
						rows.Add(GroupTap, note.ticks, "1" + laneChar, Code(tapCode, widthChar), 1f, note);
					}
					AddFlickRow(rows, note, laneChar, widthChar);
					if (i < chain.Count - 1)
					{
						// Easing shapes the segment after a point, so the last point has none (and may hold a flick).
						AddEaseRow(rows, note, laneChar, widthChar);
					}
					rows.Add(GroupSlide, note.ticks, "3" + laneChar + longNo, Code(slideCode, widthChar), note.speedRatio, note);
				}
			}
		}

		// A guide point read back from SUS takes its colour and curve from the playable note on exactly the same
		// position, if any, and later points also turn critical when the start is. SUS has no other way to set them.
		// So each point either shares the playable note's position (to take its look) or sits a fraction of a tick
		// away from every playable note (to stay plain), whichever gives the point's own look.
		private static void AddGuides(RowSet rows, List<List<MusicScoreNoteBase>> chains, Dictionary<(long, int), MusicScoreNoteBase> playablePositions, Dictionary<(long, int), int> playableCounts, List<string> warnings)
		{
			Dictionary<List<MusicScoreNoteBase>, char> longNoByChain = AssignLongNos(chains, warnings, "sus.tooManyGuides");
			Dictionary<(long, int), HashSet<int>> usedGuideSlots = new Dictionary<(long, int), HashSet<int>>();
			int lostStyleCount = 0;
			int overlapCount = 0;
			foreach (List<MusicScoreNoteBase> chain in chains)
			{
				if (!longNoByChain.TryGetValue(chain, out char longNo))
				{
					continue;
				}
				bool rootCritical = false;
				for (int i = 0; i < chain.Count; i++)
				{
					MusicScoreNoteBase note = chain[i];
					if (!TryGetLane(note, out string laneChar, out char widthChar))
					{
						continue;
					}
					(long, int) position = (note.ticks, note.laneStart);
					playablePositions.TryGetValue(position, out MusicScoreNoteBase underlying);
					int playableCount = playableCounts.TryGetValue(position, out int count) ? count : 0;
					if (!usedGuideSlots.TryGetValue(position, out HashSet<int> used))
					{
						used = new HashSet<int>();
						usedGuideSlots[position] = used;
					}

					bool inheritsCritical = i > 0 && rootCritical;
					NoteType sharedType = inheritsCritical ? NoteType.Critical : underlying?.type ?? NoteType.Default;
					NoteLineType sharedLineType = underlying?.noteLineType ?? NoteLineType.Linear;
					bool wantShared = underlying != null && note.type == sharedType && note.noteLineType == sharedLineType;
					int slot = -1;
					if (wantShared && !used.Contains(0))
					{
						slot = 0;
					}
					else
					{
						for (int candidate = underlying != null ? playableCount : 0; candidate <= MaxSubTickSlot; candidate++)
						{
							if (!used.Contains(candidate))
							{
								slot = candidate;
								break;
							}
						}
					}
					if (slot < 0)
					{
						overlapCount++;
						slot = MaxSubTickSlot;
					}
					used.Add(slot);

					bool shared = underlying != null && slot < playableCount;
					NoteType readBackType = shared ? sharedType : inheritsCritical ? NoteType.Critical : NoteType.Default;
					NoteLineType readBackLineType = shared ? sharedLineType : NoteLineType.Linear;
					if (i == 0)
					{
						rootCritical = readBackType == NoteType.Critical;
					}
					if (note.type != readBackType || note.noteLineType != readBackLineType)
					{
						lostStyleCount++;
					}

					rows.Slots[note] = slot;
					int guideCode = i == 0 ? 1 : i == chain.Count - 1 ? 2 : 5;
					rows.Add(GroupGuide, note.ticks, "9" + laneChar + longNo, Code(guideCode, widthChar), note.speedRatio, note);
				}
			}
			if (lostStyleCount > 0)
			{
				warnings.Add(L10n.Format(L10nTable, "sus.guideStyleLost", lostStyleCount));
			}
			if (overlapCount > 0)
			{
				warnings.Add(L10n.Format(L10nTable, "sus.guideOverlap", overlapCount));
			}
		}

		// SUS pairs long-note rows by a one-character id, so chains that overlap in time need different ids.
		// An id is only reused after the previous chain using it has ended, strictly before the next one starts.
		private static Dictionary<List<MusicScoreNoteBase>, char> AssignLongNos(List<List<MusicScoreNoteBase>> chains, List<string> warnings, string overflowKey)
		{
			Dictionary<List<MusicScoreNoteBase>, char> result = new Dictionary<List<MusicScoreNoteBase>, char>();
			long[] busyUntil = Enumerable.Repeat(long.MinValue, MaxLongNoCount).ToArray();
			int skipped = 0;
			foreach (List<MusicScoreNoteBase> chain in chains.OrderBy(c => c[0].ticks))
			{
				long start = chain.Min(n => n.ticks);
				long end = chain.Max(n => n.ticks);
				int slot = -1;
				for (int i = 0; i < MaxLongNoCount; i++)
				{
					if (busyUntil[i] < start)
					{
						slot = i;
						break;
					}
				}
				if (slot < 0)
				{
					skipped++;
					continue;
				}
				busyUntil[slot] = end;
				result[chain] = Base36Chars[slot];
			}
			if (skipped > 0)
			{
				warnings.Add(L10n.Format(L10nTable, overflowKey, MaxLongNoCount, skipped));
			}
			return result;
		}

		private static void AddFlickRow(RowSet rows, MusicScoreNoteBase note, string laneChar, char widthChar)
		{
			if (note.noteBaseType != MusicScoreNoteBase.NoteBaseType.Flick && note.noteBaseType != MusicScoreNoteBase.NoteBaseType.FrictionFlick)
			{
				return;
			}
			int code = note.direction switch
			{
				NoteDirection.Left => 3,
				NoteDirection.Right => 4,
				_ => 1
			};
			rows.Add(GroupDirectional, note.ticks, "5" + laneChar, Code(code, widthChar), 1f, note);
		}

		private static void AddEaseRow(RowSet rows, MusicScoreNoteBase note, string laneChar, char widthChar)
		{
			int code = note.noteLineType switch
			{
				NoteLineType.EaseIn => 2,
				NoteLineType.EaseOut => 5,
				_ => 0
			};
			if (code != 0)
			{
				rows.Add(GroupDirectional, note.ticks, "5" + laneChar, Code(code, widthChar), 1f, note);
			}
		}

		// Tap-row code that gives the note its kind and colour; 0 when a plain note needs no tap row.
		private static int GetTapCode(MusicScoreNoteBase note, bool inheritsCritical = false)
		{
			bool critical = note.type == NoteType.Critical && !inheritsCritical;
			switch (note.noteBaseType)
			{
			case MusicScoreNoteBase.NoteBaseType.Friction:
			case MusicScoreNoteBase.NoteBaseType.FrictionLong:
			case MusicScoreNoteBase.NoteBaseType.FrictionFlick:
				return critical ? 6 : 5;
			case MusicScoreNoteBase.NoteBaseType.FrictionHide:
			case MusicScoreNoteBase.NoteBaseType.FrictionHideLong:
				return critical ? 8 : 7;
			default:
				return critical ? 2 : 0;
			}
		}

		private static bool TryGetLane(MusicScoreNoteBase note, out string laneChar, out char widthChar)
		{
			int width = note.laneEnd - note.laneStart + 1;
			if (note.laneStart < 0 || note.laneStart >= LaneCount || width < 1 || note.laneStart + width > LaneCount)
			{
				laneChar = null;
				widthChar = '0';
				return false;
			}
			laneChar = LaneChars[note.laneStart].ToString();
			widthChar = WidthChars[width - 1];
			return true;
		}

		private static string Code(int code, char widthChar)
		{
			return Base36Chars[code].ToString() + widthChar;
		}

		private static string Quote(string value)
		{
			return string.IsNullOrEmpty(value) ? string.Empty : value.Replace("\"", "'").Replace("\r", " ").Replace("\n", " ");
		}

		/// <summary>
		/// Reads #WAVEOFFSET. In SUS (Ched, and usctool / the Sonolus engines that read it) it is the opposite of fillerSec:
		/// the chart starts at audio time −WAVEOFFSET.
		/// </summary>
		public static bool TryReadWaveOffset(string susText, out float waveOffset)
		{
			waveOffset = 0f;
			if (string.IsNullOrEmpty(susText))
			{
				return false;
			}
			foreach (string rawLine in susText.Split('\n'))
			{
				string line = rawLine.Trim();
				if (!line.StartsWith("#WAVEOFFSET", StringComparison.OrdinalIgnoreCase))
				{
					continue;
				}
				string value = line.Substring("#WAVEOFFSET".Length).Trim().Trim('"').Trim();
				return float.TryParse(value, NumberStyles.Float, CultureInfo.InvariantCulture, out waveOffset);
			}
			return false;
		}

		private static string FormatFloat(float value)
		{
			return value.ToString("R", CultureInfo.InvariantCulture);
		}

		private static bool TryGetFloat(object value, out float result)
		{
			switch (value)
			{
			case null:
				result = 0f;
				return false;
			case string text:
				return float.TryParse(text, NumberStyles.Float, CultureInfo.InvariantCulture, out result);
			case IConvertible convertible:
				try
				{
					result = convertible.ToSingle(CultureInfo.InvariantCulture);
					return true;
				}
				catch (Exception)
				{
					result = 0f;
					return false;
				}
			default:
				result = 0f;
				return false;
			}
		}

		private static long Gcd(long a, long b)
		{
			while (b != 0)
			{
				long t = a % b;
				a = b;
				b = t;
			}
			return Math.Abs(a);
		}

		/// <summary>Maps editor ticks to SUS bars, following the chart's time signatures.</summary>
		private sealed class BarGrid
		{
			private readonly List<(long startTicks, int startBar, long barTicks)> _segments = new List<(long, int, long)>();

			public readonly List<(int bar, float beats)> TimeSignatures = new List<(int, float)>();

			public BarGrid(List<MusicScoreEventData> sortedEvents, List<string> warnings)
			{
				_segments.Add((0L, 0, 4L * TicksPerBeat));
				TimeSignatures.Add((0, 4f));
				int movedCount = 0;
				foreach (MusicScoreEventData evt in sortedEvents)
				{
					if (evt.eventType != MusicScoreEventType.TimeSignature)
					{
						continue;
					}
					(int numerator, int denominator) = MusicScoreMakerUtility.GetTimeSignatureFromChangeValue(evt.changeValue);
					if (numerator <= 0 || denominator <= 0)
					{
						continue;
					}
					float beats = numerator * 4f / denominator;
					long barTicks = (long)Math.Round(beats * TicksPerBeat);
					if (barTicks <= 0)
					{
						continue;
					}
					Locate(Math.Max(0L, evt.ticks), out int bar, out long offset);
					// SUS can only change the time signature at a bar line.
					int applyBar = offset == 0 ? bar : bar + 1;
					if (offset != 0)
					{
						movedCount++;
					}
					long applyTicks = GetBarStartTicks(applyBar);
					_segments.RemoveAll(segment => segment.startTicks >= applyTicks);
					_segments.Add((applyTicks, applyBar, barTicks));
					TimeSignatures.RemoveAll(entry => entry.bar >= applyBar);
					TimeSignatures.Add((applyBar, beats));
				}
				if (movedCount > 0)
				{
					warnings.Add(L10n.Format(L10nTable, "sus.timeSignatureMoved", movedCount));
				}
			}

			public void Locate(long ticks, out int bar, out long offset)
			{
				(long startTicks, int startBar, long barTicks) segment = _segments[0];
				foreach ((long startTicks, int startBar, long barTicks) candidate in _segments)
				{
					if (candidate.startTicks > ticks)
					{
						break;
					}
					segment = candidate;
				}
				long elapsed = ticks - segment.startTicks;
				bar = segment.startBar + (int)(elapsed / segment.barTicks);
				offset = elapsed % segment.barTicks;
			}

			public long GetBarTicks(int bar)
			{
				long barTicks = _segments[0].barTicks;
				foreach ((long startTicks, int startBar, long barTicks) segment in _segments)
				{
					if (segment.startBar > bar)
					{
						break;
					}
					barTicks = segment.barTicks;
				}
				return barTicks;
			}

			private long GetBarStartTicks(int bar)
			{
				(long startTicks, int startBar, long barTicks) segment = _segments[0];
				foreach ((long startTicks, int startBar, long barTicks) candidate in _segments)
				{
					if (candidate.startBar > bar)
					{
						break;
					}
					segment = candidate;
				}
				return segment.startTicks + (bar - segment.startBar) * segment.barTicks;
			}
		}

		/// <summary>Collects note values per (bar, channel) and writes each as one SUS data line.</summary>
		private sealed class RowSet
		{
			private sealed class Row
			{
				public int Group;
				public int Bar;
				public string Header;
				public readonly SortedDictionary<long, string> Cells = new SortedDictionary<long, string>();
			}

			/// <summary>Sub-tick slot (0 = on the tick) for notes that are moved apart from others on the same tick.</summary>
			public readonly Dictionary<MusicScoreNoteBase, int> Slots = new Dictionary<MusicScoreNoteBase, int>();

			private readonly BarGrid _grid;
			private readonly List<string> _warnings;
			private readonly Dictionary<(int, int, string), Row> _rows = new Dictionary<(int, int, string), Row>();
			private int _outOfRangeCount;
			private int _collisionCount;

			public RowSet(BarGrid grid, List<string> warnings)
			{
				_grid = grid;
				_warnings = warnings;
			}

			public void Add(int group, long ticks, string header, string value, float speedRatio, MusicScoreNoteBase note)
			{
				if (ticks < 0)
				{
					_outOfRangeCount++;
					return;
				}
				_grid.Locate(ticks, out int bar, out long offset);
				if (bar > MaxBar)
				{
					_outOfRangeCount++;
					return;
				}
				if (!_rows.TryGetValue((group, bar, header), out Row row))
				{
					row = new Row { Group = group, Bar = bar, Header = header };
					_rows[(group, bar, header)] = row;
				}
				int slot = note != null && Slots.TryGetValue(note, out int noteSlot) ? noteSlot : 0;
				long subOffset = offset * SubTicksPerTick + slot;
				if (row.Cells.ContainsKey(subOffset))
				{
					_collisionCount++;
					return;
				}
				if (Math.Abs(speedRatio - 1f) > 1e-6f)
				{
					value += "," + FormatFloat(speedRatio);
				}
				row.Cells[subOffset] = value;
			}

			public void WriteTo(StringBuilder sb)
			{
				foreach (Row row in _rows.Values.OrderBy(r => r.Group).ThenBy(r => r.Bar).ThenBy(r => r.Header, StringComparer.Ordinal))
				{
					long barTicks = _grid.GetBarTicks(row.Bar) * SubTicksPerTick;
					long step = barTicks;
					foreach (long offset in row.Cells.Keys)
					{
						step = Gcd(step, offset);
					}
					if (step <= 0)
					{
						step = barTicks;
					}
					long count = barTicks / step;
					sb.Append('#').Append(row.Bar.ToString("D3", CultureInfo.InvariantCulture)).Append(row.Header).Append(':');
					for (long i = 0; i < count; i++)
					{
						if (row.Cells.TryGetValue(i * step, out string value))
						{
							sb.Append(value);
							if (value.IndexOf(',') >= 0)
							{
								// A ",speed" suffix runs until whitespace.
								sb.Append(' ');
							}
						}
						else
						{
							sb.Append("00");
						}
					}
					sb.Append('\n');
				}

				if (_outOfRangeCount > 0)
				{
					_warnings.Add(L10n.Format(L10nTable, "sus.outOfRange", _outOfRangeCount));
				}
				if (_collisionCount > 0)
				{
					_warnings.Add(L10n.Format(L10nTable, "sus.collision", _collisionCount));
				}
			}
		}
	}
